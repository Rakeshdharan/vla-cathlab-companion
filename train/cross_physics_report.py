"""Cross-physics table from engine eval reports: var/eval/<engine>/<model>/eval_report.json -> markdown + json.

    python -m train.cross_physics_report --evals var/eval --out reports/robosuite/cross_physics_v1
"""
import argparse
import json
from collections import Counter
from pathlib import Path
from contracts import STAGES, EvalReport
from dataengine.variation import TIERS
from eval.metrics import latency_summary, success_by_object, success_by_tier

ENGINES = {"robosuite": "robosuite (MuJoCo)", "maniskill": "ManiSkill (PhysX)", "genesis": "Genesis"}
# model -> (label, trained on); the order is the table's row order.
MODELS = {
    "expert": ("Scripted expert", "—"),
    "act_panda_pick_v1": ("ACT", "robosuite"),
    "smolvla_panda_pick_v1": ("SmolVLA", "robosuite"),
    "xvla_panda_pick_v1": ("X-VLA", "robosuite"),
    "smolvla_panda_maniskill_v1": ("SmolVLA", "maniskill"),
    "xvla_panda_maniskill_v1": ("X-VLA", "maniskill"),
    "xvla_panda_genesis_v1": ("X-VLA", "genesis"),
    "xvla_panda_pick_v2": ("X-VLA", "robosuite+maniskill+genesis"),
}


def load_reports(evals: Path) -> dict[tuple[str, str], EvalReport]:
    out = {}
    for path in sorted(Path(evals).glob("*/*/eval_report.json")):
        out[(path.parent.parent.name, path.parent.name)] = EvalReport.model_validate_json(path.read_text())
    return out


def _cell(rate: float, lo: float, hi: float, n: int) -> str:
    return f"{rate:.0%} ({lo:.0%}–{hi:.0%}, n={n})"


def overall(r: EvalReport) -> dict:
    lo, hi = r.wilson_ci()
    return {"success_rate": r.success_rate(), "ci_low": lo, "ci_high": hi, "n": len(r.episodes)}


def failed_stages(r: EvalReport) -> dict[str, int]:
    c = Counter(e.failed_stage for e in r.episodes if not e.success)
    return {s: c.get(s, 0) for s in STAGES}


def _models(reports) -> list[str]:
    seen = {m for _, m in reports}
    return [m for m in MODELS if m in seen] + sorted(seen - set(MODELS))


def _label(model: str) -> tuple[str, str]:
    return MODELS.get(model, (model, "?"))


def summarize(reports: dict[tuple[str, str], EvalReport]) -> dict:
    return {f"{eng}/{model}": {"model": model, "engine": eng, "trained_on": _label(model)[1],
                               "overall": overall(r), "per_tier": success_by_tier(r),
                               "per_object": success_by_object(r), "failed_stage": failed_stages(r),
                               "latency": latency_summary(r)}
            for (eng, model), r in reports.items()}


def render(reports: dict[tuple[str, str], EvalReport]) -> str:
    engines = [e for e in ENGINES if any(k[0] == e for k in reports)]
    models = _models(reports)
    head = "| Model | Trained on | " + " | ".join(f"eval {ENGINES[e]}" for e in engines) + " |"
    lines = ["# Cross-physics eval v1 (suite_v2: 3 objects × 5 tiers × seeds 5000–5003)", "",
             "Success with Wilson 95 % CI. **In-domain** = eval engine = training engine; the other column is "
             "cross-physics. Generated by `python -m train.cross_physics_report`.", "",
             "## Overall", "", head, "|---|---|" + "---|" * len(engines)]
    for m in models:
        label, src = _label(m)
        cells = []
        for e in engines:
            r = reports.get((e, m))
            if r is None:
                cells.append("—")
                continue
            o = overall(r)
            tag = " **in-domain**" if e in src.split("+") else ""
            cells.append(_cell(o["success_rate"], o["ci_low"], o["ci_high"], o["n"]) + tag)
        lines.append(f"| {label} (`{m}`) | {src} | " + " | ".join(cells) + " |")

    for e in engines:
        lines += ["", f"## Per tier: eval in {ENGINES[e]}", "",
                  "| Model | Trained on | " + " | ".join(TIERS) + " |", "|---|---|" + "---|" * len(TIERS)]
        for m in models:
            r = reports.get((e, m))
            if r is None:
                continue
            tiers = success_by_tier(r)
            cells = [_cell(*(tiers[t][k] for k in ("success_rate", "ci_low", "ci_high", "n"))) if t in tiers else "—"
                     for t in TIERS]
            lines.append(f"| {_label(m)[0]} | {_label(m)[1]} | " + " | ".join(cells) + " |")

    lines += ["", "## Failed stage (first stage not reached) and latency", "",
              "| Engine | Model | " + " | ".join(STAGES) + " | latency p50 / p95 ms |",
              "|---|---|" + "---|" * (len(STAGES) + 1)]
    for e in engines:
        for m in models:
            r = reports.get((e, m))
            if r is None:
                continue
            fs, lat = failed_stages(r), latency_summary(r)
            lines.append(f"| {e} | {_label(m)[0]} ({_label(m)[1]}) | " + " | ".join(str(fs[s]) for s in STAGES)
                         + f" | {lat['p50_ms']:.0f} / {lat['p95_ms']:.0f} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--evals", default="var/eval")
    ap.add_argument("--out", default="reports/robosuite/cross_physics_v1", help="writes <out>.md and <out>.json")
    args = ap.parse_args(argv)
    reports = load_reports(Path(args.evals))
    if not reports:
        raise SystemExit(f"no eval_report.json under {args.evals}/<engine>/<model>/")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".md").write_text(render(reports))
    out.with_suffix(".json").write_text(json.dumps(summarize(reports), indent=2))
    print(f"wrote {out.with_suffix('.md')} ({len(reports)} reports)")


if __name__ == "__main__":
    main()
